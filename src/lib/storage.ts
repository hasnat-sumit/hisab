import "server-only";

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import { del, get, put } from "@vercel/blob";

import { MissingConfigError } from "./db";

// Files live in a private Vercel Blob store: they have no public URL and are
// only ever served through /api/documents/[id]/file after an ownership check.
// Without a token, local development falls back to a git-ignored folder.
const LOCAL_ROOT = path.join(process.cwd(), ".data", "uploads");

function blobStoreEnabled(): boolean {
  // Vercel connects newer stores with BLOB_STORE_ID, and the Blob library then
  // authenticates by itself. Older stores have a read-write token instead.
  if (process.env.BLOB_READ_WRITE_TOKEN || process.env.BLOB_STORE_ID) return true;
  if (process.env.NODE_ENV === "production") {
    throw new MissingConfigError(
      "No Blob store is connected, so documents cannot be stored.",
    );
  }
  return false;
}

// Keys are generated by the server, but stay safe if that ever changes.
function localPath(key: string): string {
  const resolved = path.resolve(LOCAL_ROOT, key);
  if (!resolved.startsWith(LOCAL_ROOT + path.sep)) {
    throw new Error("Invalid storage key");
  }
  return resolved;
}

export async function saveFile(
  key: string,
  data: Buffer,
  contentType: string,
): Promise<void> {
  if (blobStoreEnabled()) {
    await put(key, data, {
      access: "private",
      contentType,
      addRandomSuffix: false,
    });
    return;
  }
  const filePath = localPath(key);
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, data);
}

export async function readStoredFile(
  key: string,
): Promise<ReadableStream<Uint8Array> | Uint8Array<ArrayBuffer> | null> {
  if (blobStoreEnabled()) {
    const result = await get(key, { access: "private", useCache: false });
    return result?.statusCode === 200 ? result.stream : null;
  }
  const file = await readFile(localPath(key)).catch(() => null);
  return file && new Uint8Array(file);
}

export async function deleteFile(key: string): Promise<void> {
  if (blobStoreEnabled()) {
    await del(key);
    return;
  }
  await rm(localPath(key), { force: true });
}
